#!/usr/bin/env python3
"""Write ``homebound/mapping/scan_type_table.py``: the structure and deployable types a scan paste can show.

A directional scan or combat-probe copy names each object by its type ID. Ships are in the universe
file (``ship_types``); structures, POCOs, Skyhooks, control towers and deployables are not, so this
script reads them from the SDE once and writes them into a Python module that ships with the app.
That keeps ``universe.sqlite`` at its schema: no rebuild is needed for this table.

Run it again when CCP adds a structure or deployable type:

    uv run python tools/make_scan_types.py [path/to/sde.zip]

The default SDE path is the build cache, ``data/cache/sde.zip`` (``python -m homebound.universe.build_static``
downloads it). Unpublished types are kept: the Customs Office itself (type 2233) is unpublished.
"""
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "homebound" / "mapping" / "scan_type_table.py"

# SDE category -> what a scan row of it is; None: only some groups count (see GROUP_KINDS)
CATEGORY_KINDS = {"Structure": "structure", "Orbitals": "structure", "Deployable": "deployable", "Starbase": None}
# groups that are listed differently from the rest of their category
GROUP_KINDS = {"Control Tower": "structure",          # a POS; its modules (guns, arrays) are noise
               "Mercenary Den": "structure"}          # anchored for good, reinforced like a structure


def json_lines(archive: zipfile.ZipFile, name: str):
    """Yield the records of one JSONL file of the SDE zip."""
    with archive.open(name) as member:
        for line in member:
            if line.strip():
                yield json.loads(line)


def scan_types(archive: zipfile.ZipFile) -> dict[int, tuple[str, str, str]]:
    """Return ``{type ID: (name, group name, kind)}`` for every structure and deployable type."""
    categories = {record["_key"]: record["name"]["en"] for record in json_lines(archive, "categories.jsonl")}
    groups = {}
    for record in json_lines(archive, "groups.jsonl"):
        category = categories.get(record.get("categoryID"))
        if category not in CATEGORY_KINDS:
            continue
        name = record["name"]["en"]
        kind = GROUP_KINDS.get(name, CATEGORY_KINDS[category])
        if kind:
            groups[record["_key"]] = (name, kind)
    types = {}
    for record in json_lines(archive, "types.jsonl"):
        group = groups.get(record.get("groupID"))
        name = (record.get("name") or {}).get("en")
        if group and name:
            types[record["_key"]] = (name, group[0], group[1])
    return dict(sorted(types.items()))


def main() -> int:
    """Write the module from the SDE given on the command line (or the build cache)."""
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "cache" / "sde.zip"
    with zipfile.ZipFile(source) as archive:
        types = scan_types(archive)
    lines = ['"""Structure and deployable types by type ID: ``{id: (name, group, kind)}``.',
             "",
             "Generated by ``tools/make_scan_types.py`` from the SDE; don't edit by hand. Ships are not here: they",
             'come from the universe file (``Universe.ship_name``)."""',
             "",
             "SCAN_TYPES: dict[int, tuple[str, str, str]] = {"]
    lines += [f"    {type_id}: {entry!r}," for type_id, entry in types.items()]
    lines.append("}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(types)} types -> {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
